//! Developer tooling only; schema fingerprints never participate in handoff negotiation.
import { createHash, randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import type { Kind, Revision } from "../src/persist/formats";
import * as formats from "../src/persist/formats";

export function structures(root: string): Record<string, string> {
  return Object.fromEntries(
    ["checkpoint", "handoff", "protocol", "viewer"].map(name => {
      const schema = readFileSync(join(root, "src/fixtures", `${name}.schema`), "utf8")
        .split("\n")
        .map(line => line.trim())
        .filter(Boolean)
        .sort()
        .join("\n");
      return [name, createHash("sha256").update(schema).digest("hex")];
    }),
  );
}
export function draft(parent: string, description: string, kind: "state" | "workspaces" = "state") {
  description = description.trim();
  if (!/^[a-f0-9]{12}$/.test(parent) || !description || /[\r\n]/.test(description)) throw Error("InvalidStateRevision");
  const id = randomBytes(6).toString("hex"),
    slug =
      description
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "_")
        .replace(/^_|_$/g, "")
        .slice(0, 48) || "state_change",
    name = `r_${id}_${slug}`;
  return {
    id,
    name,
    source: `import type { Revision } from "../formats";

export const revision: Revision = {
  id: ${JSON.stringify(id)},
  parent: ${JSON.stringify(parent)},
  description: ${JSON.stringify(description)},
  // ${kind === "state" ? "Replace these resets to preserve auxiliary state across this revision." : "Preserve workspace identities while transforming their saved fields."}
  up: ${kind === "state" ? "() => null" : "value => value"},
  down: ${kind === "state" ? "() => null" : "value => value"},
};
`,
  };
}
export function registry(names: readonly string[], heads: Record<Kind, string>): string {
  if (Object.values(heads).some(head => !names.includes(head))) throw Error("MissingStateHead");
  return `//! Generated by tools/state_revision.ts.
import * as formats from "./formats";
${[...names]
  .sort()
  .map(name => `import * as ${name} from "./revisions/${name}";`)
  .join("\n")}

export const revisions = [${[...names]
    .sort()
    .map(name => `${name}.revision`)
    .join(", ")}];
export const heads = {
${Object.entries(heads)
  .map(([kind, name]) => `  ${kind}: ${name}.revision.id,`)
  .join("\n")}
};
export const current = heads.state;
const histories = formats.histories(heads, revisions);
export const history = histories.state;
export const checkpoint = histories.checkpoint;
export const handoff = histories.handoff;
export const workspaces = histories.workspaces;
`;
}
export async function create(root: string, description: string, kind: "state" | "workspaces" = "state") {
  const directory = join(root, "src/persist/revisions"),
    names = readdirSync(directory)
      .filter(name => /^r_[a-f0-9]{12}_[a-z0-9_]+\.ts$/.test(name))
      .map(name => name.slice(0, -3)),
    entries = await Promise.all(
      names.map(async name => {
        const module = await import(pathToFileURL(join(directory, name + ".ts")).href);
        return { name, revision: module.revision as Revision };
      }),
    );
  const heads = Object.fromEntries(
    [
      ...readFileSync(join(root, "src/persist/state_formats.ts"), "utf8").matchAll(
        /\b(state|checkpoint|handoff|workspaces): (\w+)\.revision\.id/g,
      ),
    ].map(match => [match[1], match[2]]),
  ) as Record<Kind, string>;
  if (["state", "checkpoint", "handoff", "workspaces"].some(kind => !heads[kind as Kind]))
    throw Error("MissingStateHead");
  const ids = Object.fromEntries(
    Object.entries(heads).map(([kind, name]) => {
      const entry = entries.find(entry => entry.name === name);
      if (!entry) throw Error("MissingStateHead");
      return [kind, entry.revision.id];
    }),
  ) as Record<Kind, string>;
  const histories = formats.histories(
      ids,
      entries.map(entry => entry.revision),
    ),
    parent = histories[kind].current,
    next = draft(parent, description, kind),
    snapshot = { parent, structures: structures(root) },
    fixtures = join(root, "src/fixtures/state_revisions");
  mkdirSync(fixtures, { recursive: true });
  writeFileSync(join(directory, next.name + ".ts"), next.source, { flag: "wx" });
  writeFileSync(join(fixtures, next.id + ".json"), JSON.stringify(snapshot, null, 2) + "\n", { flag: "wx" });
  writeFileSync(
    join(root, "src/persist/state_formats.ts"),
    registry([...names, next.name], { ...heads, [kind]: next.name }),
  );
  return next;
}
