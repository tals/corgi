import { expect, test } from "bun:test";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { conversations } from "./search";

const command = `FOO="a b" bun test src/example.test.ts`;
const decoded = (...records: object[]) =>
  conversations.jsonl(records.map(r => JSON.stringify(r) + "\n").join(""), true);
const user = (content: unknown, extra: object = {}) => ({ type: "user", message: { role: "user", content }, ...extra });

test("decodes Claude tool use and text results, excluding metadata and images", () => {
  const assistant = {
    type: "assistant",
    message: {
      content: [
        { type: "thinking", thinking: "private" },
        { type: "tool_use", name: "Bash", input: { command } },
      ],
    },
  };
  const result = user([
    {
      type: "tool_result",
      content: [
        { type: "text", text: "result" },
        { type: "image", source: "secret" },
      ],
    },
  ]);
  expect(decoded(assistant, result).tools!.map(t => t.text)).toEqual([`Bash\ncommand: ${command}`, "result"]);
  expect(decoded({ ...assistant, isSidechain: true }, { ...assistant, isMeta: true }).tools).toEqual([]);
});

test("errors, empty success and missing results stay distinct without inventing exit codes", () => {
  const { tools } = decoded(
    {
      type: "assistant",
      message: {
        content: [
          { type: "tool_use", id: "fail", name: "Bash", input: { command: "gh pr create" } },
          { type: "tool_use", id: "ok", name: "Bash", input: { command: "true" } },
          { type: "tool_use", id: "pending", name: "Bash", input: { command: "long-task" } },
        ],
      },
    },
    user([{ type: "tool_result", tool_use_id: "ok", is_error: false, content: "" }]),
    user([{ type: "tool_result", tool_use_id: "fail", is_error: true, content: "failed" }]),
  );
  expect(tools!.slice(0, 3).map(r => [r.tool!.status, r.tool!.exit_code])).toEqual([
    ["error", null],
    ["success", null],
    [null, null],
  ]);
  expect(tools![3].tool).toMatchObject({ kind: "result", name: "Bash", call_ref: "1", result_ref: "2" });
});

test("a slash command keeps the arguments the user typed, and one without them is left out", () => {
  const { messages } = decoded(
    user(
      "<command-message>compact</command-message>\n<command-name>/compact</command-name>\n<command-args>keep the tab fix</command-args>",
    ),
    user(
      "<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>",
    ),
    user("<system-reminder>context</system-reminder>"),
    user("Caveat: The messages below were generated by the user while running local commands."),
  );
  expect(messages.map(m => m.text)).toEqual(["/compact keep the tab fix"]);
});

test("finds each project's session transcripts, not subagents' or SDK runs'", async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "corgi-claude-search-")),
    project = path.join(root, "projects", "-work-app");
  try {
    const transcript = (file: string, record: object) => {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, JSON.stringify({ type: "user", cwd: "/work/app", ...record }) + "\n");
    };
    transcript(path.join(project, "one.jsonl"), { sessionId: "one" });
    transcript(path.join(project, "one", "subagents", "agent-a.jsonl"), { sessionId: "one", isSidechain: true });
    transcript(path.join(project, "deep", "two.jsonl"), { sessionId: "two" });
    transcript(path.join(project, "sdk.jsonl"), { sessionId: "sdk", entrypoint: "sdk-cli" });
    const excluded: string[] = [];
    const found = await conversations.discover(root, {
      known: () => undefined,
      skipped: () => false,
      exclude: source => void excluded.push(path.basename(source)),
      warn() {},
      claim: () => true,
      checking() {},
      async checked() {},
    });
    expect(found.map(f => [f.session, f.cwd])).toEqual([["one", "/work/app"]]);
    expect(excluded).toEqual(["sdk.jsonl"]);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("a command the user ran with ! is a user-shell call, paired with its output", () => {
  const { messages, tools } = decoded(
    { type: "user", uuid: "in", message: { role: "user", content: "<bash-input>git status</bash-input>" } },
    {
      type: "user",
      uuid: "out",
      parentUuid: "in",
      message: {
        role: "user",
        content: "<bash-stdout>On branch main</bash-stdout><bash-stderr>warning: x</bash-stderr>",
      },
    },
  );
  expect(messages).toEqual([]);
  expect(tools!.map(t => [t.text, t.tool!.kind, t.tool!.name, t.tool!.call_ref, t.tool!.result_ref])).toEqual([
    ["user-shell\ncommand: git status", "call", "user-shell", "1", "2"],
    ["On branch main\nwarning: x", "result", "user-shell", "1", "2"],
  ]);
});
